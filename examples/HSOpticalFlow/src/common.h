// Align up n to the nearest multiple of m
static inline int iAlignUp(int n, int m) {
	int mod = n % m;

	if (mod)
		return n + m - mod;
	else
		return n;
}

// round up n/m
inline int iDivUp(int n, int m) { return (n + m - 1) / m; }

// swap two values
#define Swap(x, y, T)  \
	do {               \
		T Swap = x;    \
		x      = y;    \
		y      = Swap; \
	} while (0)

